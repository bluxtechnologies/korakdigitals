import * as React from 'react';
import { Head, router, usePage } from '@inertiajs/react';
import AdminAppShell from '@/components/layout/AdminAppShell';
import { UserPortfolioHeader } from '@/components/admin/UserPortfolioHeader';
import { Button } from '@/components/ui/Button';
import { Badge } from '@/components/ui/Badge';
import { useToast } from '@/components/ui/Toast';

export default function UserPortfolioApiKeys() {
    const { props } = usePage<any>();
    const user = props.userPortfolio;
    const apiKeysList = props.apiKeys || [];
    const toast = useToast();

    const [revokingId, setRevokingId] = React.useState<number | null>(null);

    const handleRevoke = (keyId: number, prefix: string) => {
        if (!confirm(`Are you sure you want to revoke API Key ${prefix}? This action cannot be undone.`)) return;

        setRevokingId(keyId);
        router.post(`/admin/users/${user.id}/api-keys/${keyId}/revoke`, {}, {
            onSuccess: () => {
                setRevokingId(null);
                toast.success(`API Key ${prefix} revoked successfully!`);
            },
            onError: (err: any) => {
                setRevokingId(null);
                toast.error(err.message || 'Failed to revoke API key.');
            }
        });
    };

    return (
        <>
            <Head title={`User API Keys: ${user.name}`} />
            <div className="space-y-6 animate-fadeIn select-none">
                
                <UserPortfolioHeader user={user} />

                <div>
                    <h3 className="text-lg font-black tracking-tight text-text-primary">Developer Secret API Keys</h3>
                    <p className="text-xs font-semibold text-text-secondary">Manage REST API keys generated by this customer for external application integrations.</p>
                </div>

                <div className="bg-bg-surface border border-border-subtle rounded-md overflow-hidden shadow-xs">
                    {apiKeysList.length === 0 ? (
                        <div className="p-8 text-center text-xs font-semibold text-text-muted">No developer API keys generated by this user.</div>
                    ) : (
                        <div className="overflow-x-auto">
                            <table className="w-full text-left text-xs">
                                <thead>
                                    <tr className="bg-bg-base text-text-secondary uppercase text-[10px] font-extrabold border-b border-border-subtle">
                                        <th className="px-6 py-3.5">Key Name</th>
                                        <th className="px-6 py-3.5">Token Prefix</th>
                                        <th className="px-6 py-3.5">Created At</th>
                                        <th className="px-6 py-3.5">Last Used</th>
                                        <th className="px-6 py-3.5">Status</th>
                                        <th className="px-6 py-3.5 text-center">Action</th>
                                    </tr>
                                </thead>
                                <tbody className="divide-y divide-border-subtle font-medium text-text-secondary">
                                    {apiKeysList.map((k: any) => (
                                        <tr key={k.id} className="hover:bg-bg-surface-hover transition-colors">
                                            <td className="px-6 py-3.5 font-bold text-text-primary">{k.name}</td>
                                            <td className="px-6 py-3.5 font-mono font-bold text-brand">{k.key_prefix}••••••••</td>
                                            <td className="px-6 py-3.5 font-mono text-[11px] text-text-muted">
                                                {new Date(k.created_at).toLocaleDateString()}
                                            </td>
                                            <td className="px-6 py-3.5 font-mono text-[11px] text-text-muted">
                                                {k.last_used_at ? new Date(k.last_used_at).toLocaleString() : 'Never'}
                                            </td>
                                            <td className="px-6 py-3.5">
                                                <Badge variant={k.is_active ? 'success' : 'error'} className="text-[9px] uppercase font-extrabold">
                                                    {k.is_active ? 'Active' : 'Revoked'}
                                                </Badge>
                                            </td>
                                            <td className="px-6 py-3.5 text-center">
                                                {k.is_active && (
                                                    <Button
                                                        size="sm"
                                                        variant="outline"
                                                        className="text-xs text-error border-error-border hover:bg-error-bg font-bold rounded-md"
                                                        onClick={() => handleRevoke(k.id, k.key_prefix)}
                                                        isLoading={revokingId === k.id}
                                                    >
                                                        Revoke Key
                                                    </Button>
                                                )}
                                            </td>
                                        </tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    )}
                </div>

            </div>
        </>
    );
}

UserPortfolioApiKeys.layout = (page: React.ReactNode) => <AdminAppShell>{page}</AdminAppShell>;
